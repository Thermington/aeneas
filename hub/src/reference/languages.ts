/** One language by its ISO 639-3 code; an unknown code is its own tag and name. */
export function language(code: string): Language {
  const row = TABLE[code];
  return row ? { code, tag: row[0], name: row[1], native: row[2] } : { code, tag: code, name: code, native: code };
}

export function knownLanguage(code: unknown): code is string { return typeof code === "string" && Object.hasOwn(TABLE, code); }

/** Every code in the table. */
export function languageCodes(): string[] { return Object.keys(TABLE); }

/**
 * A language named by its code (`eng`), tag (`en`) or name in English or in itself (`English`, `español`), for the
 * assistant's `lang`. Null when nothing matches.
 */
export function findLanguage(given: string): string | null {
  const v = given.trim().toLowerCase();
  if (!v) return null;
  if (Object.hasOwn(TABLE, v)) return v;
  for (const [code, [tag, name, native]] of Object.entries(TABLE)) {
    if (tag.toLowerCase() === v || name.toLowerCase() === v || native.toLowerCase() === v) return code;
  }
  return null;
}

/** Other spellings of language names that wikis put after a page's title ("Mirrors (简体中文)"). */
const OTHER_NAMES = ["简体中文", "正體中文", "繁體中文", "中文（简体）", "中文（繁體）", "português do brasil", "português (brasil)", "bahasa indonesia", "bahasa melayu", "srpski", "slovenský", "norsk"];

let names: Set<string> | null = null;
/**
 * Whether a text is a language's name in itself, letter case aside ("Русский", "Magyar"): wikis such as ArchWiki name
 * a page's copy in another language that way. Names in English are left out, so "Mercury (Latin)" is not taken for one.
 */
export function isLanguageName(text: string): boolean {
  if (!names) {
    names = new Set(OTHER_NAMES);
    for (const [, name, native] of Object.values(TABLE)) if (native !== name || native === "English") names.add(native.toLowerCase());
  }
  return names.has(text.trim().toLowerCase());
}
